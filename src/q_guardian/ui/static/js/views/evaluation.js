/* Q-Guardian Console — Evaluation view.
 * The evaluation report written by scripts/evaluate_pipeline.py, read from
 * docs/output/evaluation/report.json via /console/research. When no report
 * exists the page says so truthfully and explains how to generate one.
 */
(function () {
  "use strict";

  var QG = window.QG || (window.QG = {});
  QG.views = QG.views || {};
  var api = QG.api;
  var U = QG.ui;

  function metricRows(report) {
    var rows = [];
    var cross = (report.cross_validation || {}).metrics || {};
    Object.keys(cross).forEach(function (provider) {
      var metrics = cross[provider] || {};
      Object.keys(metrics).forEach(function (metricName) {
        var stat = metrics[metricName] || {};
        var mean = stat.mean;
        rows.push({
          provider: provider,
          metric: metricName,
          stat: stat,
        });
      });
    });
    if (!rows.length) return null;
    return rows.map(function (row) {
      return [
        { value: row.provider, cls: "cell-strong" },
        row.metric,
        { value: typeof row.stat.mean === "number" ? row.stat.mean.toFixed(4) : "—", cls: "cell-mono" },
        { value: typeof row.stat.std === "number" ? row.stat.std.toFixed(4) : "—", cls: "cell-mono" },
        { value: typeof row.stat.min === "number" ? row.stat.min.toFixed(4) : "—", cls: "cell-mono" },
        { value: typeof row.stat.max === "number" ? row.stat.max.toFixed(4) : "—", cls: "cell-mono" },
      ];
    });
  }

  function reportBody(report) {
    if (!report) return U.emptyState("No evaluation report content available.");
    var kv = [];
    if (report.config) {
      Object.keys(report.config).forEach(function (key) {
        kv.push({
          label: key.replace(/_/g, " "),
          value: typeof report.config[key] === "object" ? JSON.stringify(report.config[key]) : report.config[key],
          mono: true,
        });
      });
    }
    var mean = report.cross_validation && report.cross_validation.mean;
    if (mean) {
      Object.keys(mean).forEach(function (key) {
        kv.push({ label: "mean " + key.replace(/_/g, " "), value: mean[key], mono: true });
      });
    }
    var metricRowsHtml = metricRows(report);
    return (
      (kv.length ? '<div class="card-head"><div class="card-title">Report Configuration</div></div>' + U.keyValue(kv) : "") +
      (metricRowsHtml
        ? '<div class="card-head" style="margin-top:18px;"><div class="card-title">Cross-Validation Metrics</div></div>' +
          U.table(["Provider", "Metric", "Mean", "Std", "Min", "Max"], metricRowsHtml)
        : "") +
      '<div class="card-head" style="margin-top:18px;"><div class="card-title">Raw Report</div></div>' +
      U.codeBlock(report)
    );
  }

  QG.views.evaluation = {
    title: "Evaluation",
    group: "research",
    render: async function (el) {
      el.innerHTML = U.loadingState("Reading evaluation report…");
      try {
        var payload = await api.get(api.endpoints.research);
        var research = api.data(payload) || {};
        var evaluation = research.evaluation || {};
        var attached = [];

        if (evaluation.scores_csv) attached.push(U.badge("scores.csv", "success"));
        if (evaluation.report_md) attached.push(U.badge("report.md", "success"));

        var body;
        if (evaluation.present) {
          body =
            '<div class="grid grid-3">' +
            U.statCard("Report", "Present", evaluation.generated_at ? U.fmtDateTime(evaluation.generated_at) : "", "success") +
            U.statCard("Scores CSV", evaluation.scores_csv ? "Yes" : "No", "attached", evaluation.scores_csv ? "success" : "low") +
            U.statCard("Report MD", evaluation.report_md ? "Yes" : "No", "attached", evaluation.report_md ? "success" : "low") +
            "</div>" +
            (evaluation.note ? U.note(evaluation.note) : "") +
            '<div class="card">' + reportBody(evaluation.report) + "</div>";
        } else {
          body =
            '<div class="grid grid-3">' +
            U.statCard("Report", "Not present", "", "low") +
            U.statCard("Scores CSV", "No", "", "low") +
            U.statCard("Report MD", "No", "", "low") +
            "</div>" +
            U.note(evaluation.note || "No evaluation report found on disk.");
        }

        el.innerHTML =
          '<div class="page-head">' +
          "<div>" +
          '<h2 class="page-title">Evaluation</h2>' +
          '<p class="page-sub">Results of cross-validation and ablation studies, generated by the evaluation pipeline. The console reads the saved report only.</p>' +
          "</div>" +
          '<button type="button" class="btn ghost" id="refreshEvaluation">Refresh</button>' +
          "</div>" +
          body;

        el.querySelector("#refreshEvaluation").addEventListener("click", function () {
          QG.views.evaluation.render(el);
        });
      } catch (err) {
        el.innerHTML = U.errorState(err.message || "Could not read the evaluation report.");
      }
    },
  };
})();
